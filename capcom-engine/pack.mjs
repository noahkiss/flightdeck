// Pack the engine folder a release ships (docs/specs/ci-release.md 7.2, 7.8):
//
//   node pack.mjs [out]      (default dist/capcom; run `npm run build` first)
//
// The folder holds the bundle, the npm manifest of the SDKs it loads, and NOTICE: the licence
// texts of every package the bundle holds, read from node_modules at the locked versions. The
// package list comes from the build's metafile, so it is exactly what esbuild put in the bundle.
// Fails when a bundled package has no licence file, or when an SDK that must stay external is
// in the bundle.
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = fileURLToPath(new URL('.', import.meta.url));
const out = resolve(process.argv[2] ?? join(here, 'dist', 'capcom'));
const dist = join(here, 'dist');
const external = ['@anthropic-ai/claude-agent-sdk', '@openai/codex-sdk'];
const licenceRE = /^(licen[cs]e|copying|notice)([-._].*)?$/i;

const fail = (msg) => {
  console.error(`pack: ${msg}`);
  process.exit(1);
};

if (!existsSync(join(dist, 'meta.json'))) fail('no dist/meta.json: run `npm run build` first');
const meta = JSON.parse(readFileSync(join(dist, 'meta.json'), 'utf8'));

// Each bundled input under node_modules names its package by the last node_modules segment of
// its path, so a nested copy (a/node_modules/b) is its own package.
const roots = new Map();
for (const input of Object.keys(meta.inputs)) {
  const m = input.match(/^(.*node_modules\/((?:@[^/]+\/)?[^/]+))\//);
  if (m) roots.set(m[1], m[2]);
}
for (const name of external) {
  if ([...roots.values()].includes(name)) fail(`${name} is in the bundle; it must stay external`);
}

const entries = [];
const missing = [];
for (const [root, name] of roots) {
  const pkg = JSON.parse(readFileSync(join(here, root, 'package.json'), 'utf8'));
  const files = readdirSync(join(here, root)).filter((f) => licenceRE.test(f)).sort();
  if (files.length === 0) missing.push(name);
  const licence = typeof pkg.license === 'string' ? pkg.license : pkg.license?.type ?? 'see the text below';
  let source = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url ?? pkg.homepage ?? '';
  source = source.replace(/^git\+/, '').replace(/\.git$/, '');
  entries.push({ name, version: pkg.version, licence, source, root, files });
}
if (missing.length) fail(`no licence file in the bundled package(s): ${missing.join(', ')}`);
entries.sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

const lines = [
  'Third-party notices for the Capcom engine (capcom/gff-hab-capcom.mjs)',
  '',
  "The engine is Flightdeck's own code, under the MIT License (LICENSE in the folder above).",
  entries.length
    ? 'It bundles the JavaScript packages below. Each entry names the package, its version, its\n' +
      'source, its licence, then the licence text.'
    : 'The bundle holds no third-party package.',
  '',
  'The engine loads the Claude Agent SDK (@anthropic-ai/claude-agent-sdk) and the Codex SDK',
  '(@openai/codex-sdk). They are not in this folder: `gff-hab install` runs `npm ci --omit=dev`',
  'in its copy of the folder, which downloads them from npm, at the versions package-lock.json',
  'pins, under their own licences.',
  '',
  'Generated by capcom-engine/pack.mjs. Do not edit.',
];
if (entries.length) lines.push('', 'Contents', '', ...entries.map((e) => `  ${e.name}`));
const seen = new Map();
for (const e of entries) {
  lines.push('', '='.repeat(78), e.name, `Version: ${e.version}`);
  if (e.source) lines.push(`Source: ${e.source}`);
  lines.push(`Licence: ${e.licence}`, 'In: gff-hab-capcom.mjs');
  for (const f of e.files) {
    const text = readFileSync(join(here, e.root, f), 'utf8').trim();
    const key = text.replace(/\s+/g, ' ');
    lines.push('', `--- ${e.name}/${f}`);
    if (seen.has(key)) lines.push(`(The same text as ${seen.get(key)} above.)`);
    else {
      seen.set(key, `${e.name} ${f}`);
      lines.push(text);
    }
  }
}

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
cpSync(join(dist, 'gff-hab-capcom.mjs'), join(out, 'gff-hab-capcom.mjs'));
cpSync(join(here, 'package.json'), join(out, 'package.json'));
cpSync(join(here, 'package-lock.json'), join(out, 'package-lock.json'));
writeFileSync(join(out, 'NOTICE'), lines.join('\n') + '\n');
console.log(`pack: ${out} (${entries.length} bundled packages in NOTICE)`);
