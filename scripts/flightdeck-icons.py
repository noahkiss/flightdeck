#!/usr/bin/env python3
"""Generate flightdeck's app-icon code from scripts/flightdeck-icons.json.

The JSON lists every icon: its alternate-icon name, its label in the picker and
its picker section. The primary icon is AppIcon.icon; the alternates are
rootshell/Flightdeck/Icons/AltIcons/<name>.icon. Each icon has a preview image
set, <name>Preview (FDAppIconPreview for the primary icon), in the app catalog
and in the widget catalog.

Run with no arguments to rewrite the generated files:
  rootshell/Flightdeck/Icons/AppIconVariant+Flightdeck.swift
  Configuration/FlightdeckIcons.xcconfig
Run with --check to exit 1 when a generated file is stale or an icon bundle or
preview is missing or unlisted (CI runs this).
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "scripts" / "flightdeck-icons.json"
ICONS = ROOT / "rootshell" / "Flightdeck" / "Icons"
ALT = ICONS / "AltIcons"
APP_CATALOG = ICONS / "FlightdeckIcons.xcassets"
WIDGET_CATALOG = ROOT / "SessionActivityWidget" / "Flightdeck" / "FlightdeckIconPreviews.xcassets"
PRIMARY = ROOT / "AppIcon.icon"
SWIFT = ICONS / "AppIconVariant+Flightdeck.swift"
XCCONFIG = ROOT / "Configuration" / "FlightdeckIcons.xcconfig"
PRIMARY_PREVIEW = "FDAppIconPreview"

HEADER = "Generated by scripts/flightdeck-icons.py from scripts/flightdeck-icons.json. Do not edit."


def swift_string(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def case_name(name: str) -> str:
    assert re.fullmatch(r"FD[A-Za-z0-9]+", name), name
    return "fd" + name[2:]


def load():
    data = json.loads(DATA.read_text())
    icons = data["icons"]
    names = [i["name"] for i in icons]
    assert len(set(names)) == len(names), "duplicate icon names"
    assert data["default"] in names, "default is not an icon"
    for i in icons:
        assert i["section"] in data["sections"], i
    return data


def generate_swift(data) -> str:
    default = data["default"]
    icons = data["icons"]
    alts = [i for i in icons if i["name"] != default]
    label = {i["name"]: i["label"] for i in icons}
    counts = {}
    for i in icons:
        counts[i["label"]] = counts.get(i["label"], 0) + 1

    def case(name):
        return "defaultIcon" if name == default else case_name(name)

    def intent_label(i):
        # Shortcuts shows one flat list, so repeated labels name their section.
        return i["label"] if counts[i["label"]] == 1 else f'{i["label"]} ({i["section"]})'

    out = [f"// {HEADER}", "", "#if FLIGHTDECK", "import AppIntents", "import Foundation", ""]
    out += [
        "extension AppIconManager {",
        "    /// FlightDeck's app icons. Replaces upstream's variant list, which",
        "    /// AppIconManager.swift compiles only without FLIGHTDECK. Raw values are",
        "    /// the alternate-icon names in FLIGHTDECK_ALTERNATE_APPICON_NAMES; the",
        "    /// empty string is the primary icon, AppIcon.icon.",
        "    enum AppIconVariant: String, CaseIterable, Codable, Identifiable, Sendable {",
        '        case defaultIcon = ""',
    ]
    out += [f"        case {case_name(i['name'])} = {swift_string(i['name'])}" for i in alts]
    out += ["", "        var id: String { rawValue }", ""]
    out += [
        "        /// One picker section.",
        "        struct Section: Identifiable, Sendable {",
        "            let title: String",
        "            let variants: [AppIconVariant]",
        "            var id: String { title }",
        "        }",
        "",
        "        static let sections: [Section] = [",
    ]
    for s in data["sections"]:
        members = ", ".join("." + case(i["name"]) for i in icons if i["section"] == s)
        out.append(f"            Section(title: {swift_string(s)}, variants: [{members}]),")
    out += ["        ]", ""]
    out += [
        "        // Upstream's picker lists, kept so upstream call sites still compile.",
        "        static let standardVariants: [AppIconVariant] = sections[0].variants",
        "        static let radicalOfTheUnknownVariants: [AppIconVariant] = []",
        "",
        "        /// Label in the picker.",
        "        var displayName: String {",
        "            switch self {",
    ]
    out.append(f"            case .defaultIcon: return {swift_string(label[default])}")
    out += [f"            case .{case_name(i['name'])}: return {swift_string(i['label'])}" for i in alts]
    out += [
        "            }",
        "        }",
        "",
        "        /// Image set with the flat preview, in the app and widget catalogs.",
        "        var previewAssetName: String {",
        f"            self == .defaultIcon ? {swift_string(PRIMARY_PREVIEW)} : rawValue + \"Preview\"",
        "        }",
        "",
        "        /// Value passed to `UIApplication.setAlternateIconName(_:)`.",
        "        var alternateIconName: String? {",
        "            self == .defaultIcon ? nil : rawValue",
        "        }",
        "",
        "        init(alternateIconName: String?) {",
        "            guard let name = alternateIconName,",
        "                  let variant = AppIconVariant(rawValue: name) else {",
        "                self = .defaultIcon",
        "                return",
        "            }",
        "            self = variant",
        "        }",
        "    }",
        "}",
        "",
        "extension AppIconManager.AppIconVariant: AppEnum {",
        "    nonisolated static var typeDisplayRepresentation: TypeDisplayRepresentation {",
        '        TypeDisplayRepresentation(name: "App Icon")',
        "    }",
        "",
        "    nonisolated static var caseDisplayRepresentations: [AppIconManager.AppIconVariant: DisplayRepresentation] {",
        "        [",
    ]
    out += [f"            .{case(i['name'])}: {swift_string(intent_label(i))}," for i in icons]
    out += ["        ]", "    }", "}", "#endif", ""]
    return "\n".join(out)


def generate_xcconfig(data) -> str:
    names = " ".join(i["name"] for i in data["icons"] if i["name"] != data["default"])
    return (
        f"// {HEADER}\n"
        "//\n"
        "// Alternate app icons. The app targets read this variable through\n"
        "// ASSETCATALOG_COMPILER_ALTERNATE_APPICON_NAMES.\n"
        f"FLIGHTDECK_ALTERNATE_APPICON_NAMES = {names}\n"
    )


def asset_problems(data) -> list[str]:
    problems = []
    default = data["default"]
    wanted = {i["name"] for i in data["icons"] if i["name"] != default}
    bundles = {p.stem for p in ALT.glob("*.icon")}
    problems += [f"AltIcons: missing {n}.icon" for n in sorted(wanted - bundles)]
    problems += [f"AltIcons: unlisted {n}.icon" for n in sorted(bundles - wanted)]
    for bundle in [PRIMARY] + [ALT / f"{n}.icon" for n in sorted(wanted & bundles)]:
        try:
            doc = json.loads((bundle / "icon.json").read_text())
        except (OSError, ValueError) as e:
            problems.append(f"{bundle.name}: unreadable icon.json ({e})")
            continue
        for group in doc.get("groups", []):
            for layer in group.get("layers", []):
                if not (bundle / "Assets" / layer["image-name"]).is_file():
                    problems.append(f"{bundle.name}: missing Assets/{layer['image-name']}")
    previews = {PRIMARY_PREVIEW} | {f"{n}Preview" for n in wanted}
    for catalog in (APP_CATALOG, WIDGET_CATALOG):
        have = {p.stem for p in catalog.glob("*.imageset")}
        rel = catalog.relative_to(ROOT)
        problems += [f"{rel}: missing {n}.imageset" for n in sorted(previews - have)]
        problems += [f"{rel}: unlisted {n}.imageset" for n in sorted(have - previews)]
    return problems


def main() -> int:
    check = "--check" in sys.argv[1:]
    data = load()
    outputs = {SWIFT: generate_swift(data), XCCONFIG: generate_xcconfig(data)}
    problems = []
    for path, text in outputs.items():
        if check:
            if not path.exists() or path.read_text() != text:
                problems.append(f"stale, rerun scripts/flightdeck-icons.py: {path.relative_to(ROOT)}")
        else:
            path.write_text(text)
    problems += asset_problems(data)
    for p in problems:
        print(p)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
