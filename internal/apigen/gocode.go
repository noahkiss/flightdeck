package apigen

import (
	"bytes"
	"fmt"
	"go/format"
	"reflect"

	"github.com/noahkiss/flightdeck/api"
)

// GoClient renders api/client_gen.go: word constants, event type constants, typed event
// decoding and a client stub per method.
func GoClient() ([]byte, error) {
	var w bytes.Buffer
	p := func(format string, args ...any) { fmt.Fprintf(&w, format, args...) }

	p("// Code generated by internal/apigen. DO NOT EDIT.\n\n")
	p("package api\n\n")
	p("import (\n\t\"context\"\n\t\"encoding/json\"\n)\n\n")

	for _, name := range sortedKeys(api.Enums) {
		p("const (\n")
		for _, v := range api.Enums[name] {
			p("\t%s%s %s = %q\n", name, camel(v, true), name, v)
		}
		p(")\n\n")
	}

	p("// Event types.\nconst (\n")
	for _, e := range api.Events {
		p("\tEvent%s EventType = %q\n", camel(string(e.Type), true), e.Type)
	}
	p(")\n\n")

	p("// DecodeData decodes e.Data into the type its event type names. It returns\n")
	p("// e.Data unchanged for an unknown event type.\n")
	p("func (e Event) DecodeData() (any, error) {\n\tswitch e.Type {\n")
	for _, e := range api.Events {
		t := reflect.TypeOf(e.Data).Name()
		p("\tcase Event%s:\n\t\tvar v %s\n\t\terr := json.Unmarshal(e.Data, &v)\n\t\treturn v, err\n", camel(string(e.Type), true), t)
	}
	p("\t}\n\treturn e.Data, nil\n}\n\n")

	p("// Caller sends one JSON-RPC request and decodes its result into result.\n")
	p("type Caller interface {\n\tCall(ctx context.Context, method string, params, result any) error\n}\n\n")
	p("// Client wraps a Caller with one typed method per API method.\n")
	p("type Client struct {\n\tCaller Caller\n}\n\n")
	for _, m := range api.Methods {
		pt := reflect.TypeOf(m.Params).Name()
		rt := reflect.TypeOf(m.Result)
		rname := rt.Name()
		if rt == rawJSONType {
			rname = "RawJSON"
		}
		p("// %s calls %s. %s\n", camel(m.Name, true), m.Name, m.Summary)
		p("func (c Client) %s(ctx context.Context, params %s) (%s, error) {\n", camel(m.Name, true), pt, rname)
		p("\tvar result %s\n\terr := c.Caller.Call(ctx, %q, params, &result)\n\treturn result, err\n}\n\n", rname, m.Name)
	}

	return format.Source(w.Bytes())
}
