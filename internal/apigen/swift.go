// Swift renders the document as one Swift source file of Codable types.
func Swift(d *Document) []byte {
	var w bytes.Buffer
	p := func(format string, args ...any) { fmt.Fprintf(&w, format, args...) }

	p("// Code generated by internal/apigen from api/schema.json. DO NOT EDIT.\n\n")
	p("import Foundation\n\n")
	p("public enum HabAPI {\n")
	p("    /// The API revision these types describe.\n")
	p("    public static let revision = %d\n", d.Revision)
	p("    /// The oldest revision the server translates down to.\n")
	p("    public static let minRevision = %d\n", d.MinRevision)
	p("    /// JSON-RPC error code of every application error.\n")
	p("    public static let errorCode = %d\n", d.ErrorCode)
	p("    /// Capability strings this revision knows.\n")
	p("    public static let capabilities: [String] = [%s]\n", quoteList(d.Capabilities))
	p("}\n\n")

	for _, name := range sortedKeys(d.Components.Schemas) {
		s := d.Components.Schemas[name]
		if s.KnownValues != nil {
			swiftWords(&w, name, s)
		} else {
			swiftStruct(&w, d, name, s)
		}
	}

	// Methods: a typed descriptor per method.
	p("/// A method with its params and result types.\n")
	p("public struct HabMethod<Params: Codable & Sendable, Result: Codable & Sendable>: Sendable {\n")
	p("    public let name: String\n")
	p("}\n\n")
	p("public enum HabMethods {\n")
	for _, m := range d.Methods {
		_, pname := d.Resolve(m.ParamsType)
		p("    /// %s\n", m.Summary)
		p("    public static let %s = HabMethod<%s, %s>(name: %q)\n", camel(m.Name, false), pname, swiftType(d, m.Result.Schema), m.Name)
	}
	p("}\n\n")

	// Notifications.
	p("public enum HabNotification {\n")
	for _, n := range d.Notifications {
		p("    public static let %s = %q\n", camel(n.Name, false), n.Name)
	}
	p("}\n\n")

	// Events: a typed enum decoded from the Event envelope.
	p("/// The data of an event, decoded by its type. Unknown types decode to `.unknown`.\n")
	p("public enum HabEvent: Sendable, Hashable {\n")
	for _, e := range d.Events {
		p("    /// %s\n", e.Summary)
		p("    case %s(%s)\n", camel(e.Type, false), swiftType(d, e.Data))
	}
	p("    case unknown(type: String, data: JSONValue)\n\n")
	p("    public init(_ event: Event) throws {\n")
	p("        switch event.type {\n")
	for _, e := range d.Events {
		p("        case %q: self = .%s(try event.data.decode(%s.self))\n", e.Type, camel(e.Type, false), swiftType(d, e.Data))
	}
	p("        default: self = .unknown(type: event.type, data: event.data)\n")
	p("        }\n")
	p("    }\n")
	p("}\n\n")

	// Frames.
	p("/// The first byte of a data connection frame. A frame is this byte, a 4-byte big-endian\n")
	p("/// payload length, then the payload.\n")
	p("public enum FrameKind: UInt8, Sendable {\n")
	for _, f := range d.Frames {
		if f.Layout != "" {
			p("    /// Binary payload: %s.\n", f.Layout)
		} else {
			_, pname := d.Resolve(f.Payload)
			p("    /// JSON payload: `%s`.\n", pname)
		}
		p("    case %s = %d\n", camel(f.Name, false), f.Kind)
	}
	p("}\n\n")

	w.WriteString(jsonValueSwift)
	return w.Bytes()
}

func swiftWords(w *bytes.Buffer, name string, s *Schema) {
	fmt.Fprintf(w, "/// An open word set: values outside the known list decode and round-trip unchanged.\n")
	fmt.Fprintf(w, "public struct %s: RawRepresentable, Codable, Sendable, Hashable {\n", name)
	fmt.Fprintf(w, "    public var rawValue: String\n")
	fmt.Fprintf(w, "    public init(rawValue: String) { self.rawValue = rawValue }\n")
	for _, v := range s.KnownValues {
		fmt.Fprintf(w, "    public static let %s = %s(rawValue: %q)\n", swiftIdent(camel(v, false)), name, v)
	}
	fmt.Fprintf(w, "}\n\n")
}

func swiftStruct(w *bytes.Buffer, d *Document, name string, s *Schema) {
	if s.Description != "" {
		fmt.Fprintf(w, "/// %s\n", s.Description)
	}
	fmt.Fprintf(w, "public struct %s: Codable, Sendable, Hashable {\n", name)
	props := sortedKeys(s.Properties)
	type field struct{ ident, json, typ string }
	var fields []field
	for _, pn := range props {
		ps := s.Properties[pn]
		t := swiftType(d, ps)
		if !contains(s.Required, pn) {
			t += "?"
		}
		f := field{swiftIdent(camel(pn, false)), pn, t}
		fields = append(fields, f)
		if ps.Description != "" {
			fmt.Fprintf(w, "    /// %s\n", ps.Description)
		}
		fmt.Fprintf(w, "    public var %s: %s\n", f.ident, f.typ)
	}
	if len(fields) > 0 {
		fmt.Fprintf(w, "\n    enum CodingKeys: String, CodingKey {\n")
		for _, f := range fields {
			fmt.Fprintf(w, "        case %s = %q\n", f.ident, f.json)
		}
		fmt.Fprintf(w, "    }\n\n")
	}
	var args, sets []string
	for _, f := range fields {
		arg := f.ident + ": " + f.typ
		if strings.HasSuffix(f.typ, "?") {
			arg += " = nil"
		}
		args = append(args, arg)
		sets = append(sets, fmt.Sprintf("        self.%s = %s\n", f.ident, f.ident))
	}
	fmt.Fprintf(w, "    public init(%s) {\n%s    }\n", strings.Join(args, ", "), strings.Join(sets, ""))
	fmt.Fprintf(w, "}\n\n")
}

func swiftType(d *Document, s *Schema) string {
	if s.Ref != "" {
		_, name := d.Resolve(s)
		return name
	}
	switch s.Type {
	case "":
		return "JSONValue"
	case "string":
		if s.ContentEncoding == "base64" {
			return "Data"
		}
		return "String"
	case "boolean":
		return "Bool"
	case "integer":
		if s.Format == "uint64" {
			return "UInt64"
		}
		return "Int"
	case "number":
		return "Double"
	case "array":
		return "[" + swiftType(d, s.Items) + "]"
	}
	panic("swift: unsupported schema type " + s.Type)
}

// camel turns snake_case, dotted or dashed words into lowerCamel (or UpperCamel).
func camel(s string, upper bool) string {
	var b strings.Builder
	next := upper
	for i, r := range s {
		if r == '_' || r == '.' || r == '-' {
			next = true
			continue
		}
		if next && (i > 0 || upper) {
			b.WriteRune(unicode.ToUpper(r))
		} else {
			b.WriteRune(r)
		}
		next = false
	}
	return b.String()
}

var swiftKeywords = map[string]bool{
	"default": true, "protocol": true, "class": true, "struct": true, "enum": true, "case": true,
	"func": true, "import": true, "init": true, "let": true, "var": true, "return": true,
	"self": true, "Self": true, "static": true, "switch": true, "true": true, "false": true,
	"nil": true, "in": true, "is": true, "as": true, "where": true, "while": true, "for": true,
	"if": true, "else": true, "do": true, "try": true, "throw": true, "throws": true,
	"repeat": true, "guard": true, "defer": true, "operator": true, "extension": true,
	"internal": true, "private": true, "public": true, "fileprivate": true, "open": true,
	"subscript": true, "typealias": true, "associatedtype": true, "inout": true, "any": true,
	"break": true, "continue": true, "fallthrough": true, "rethrows": true, "super": true, "deinit": true,
}

func swiftIdent(s string) string {
	if swiftKeywords[s] {
		return "`" + s + "`"
	}
	return s
}

func quoteList(list []string) string {
	q := make([]string, len(list))
	for i, s := range list {
		q[i] = fmt.Sprintf("%q", s)
	}
	return strings.Join(q, ", ")
}

const jsonValueSwift = `/// Any JSON value, for fields whose shape the receiver picks.
public enum JSONValue: Codable, Sendable, Hashable {
    case null
    case bool(Bool)
    /// A whole number that fits Int64. Kept exact, unlike a Double.
    case int(Int64)
    /// A whole number above Int64.max, such as a large offset. Kept exact.
    case uint(UInt64)
    /// Any other number.
    case number(Double)
    case string(String)
    case array([JSONValue])
    case object([String: JSONValue])

    public init(from decoder: Decoder) throws {
        let c = try decoder.singleValueContainer()
        if c.decodeNil() {
            self = .null
        } else if let v = try? c.decode(Bool.self) {
            self = .bool(v)
        } else if let v = try? c.decode(Int64.self) {
            self = .int(v)
        } else if let v = try? c.decode(UInt64.self) {
            self = .uint(v)
        } else if let v = try? c.decode(Double.self) {
            self = .number(v)
        } else if let v = try? c.decode(String.self) {
            self = .string(v)
        } else if let v = try? c.decode([JSONValue].self) {
            self = .array(v)
        } else {
            self = .object(try c.decode([String: JSONValue].self))
        }
    }

    public func encode(to encoder: Encoder) throws {
        var c = encoder.singleValueContainer()
        switch self {
        case .null: try c.encodeNil()
        case .bool(let v): try c.encode(v)
        case .int(let v): try c.encode(v)
        case .uint(let v): try c.encode(v)
        case .number(let v): try c.encode(v)
        case .string(let v): try c.encode(v)
        case .array(let v): try c.encode(v)
        case .object(let v): try c.encode(v)
        }
    }

    /// Decodes this value as T, by a round trip through JSON.
    public func decode<T: Decodable>(_ type: T.Type) throws -> T {
        try JSONDecoder().decode(T.self, from: JSONEncoder().encode(self))
    }
}
`
