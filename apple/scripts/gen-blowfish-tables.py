#!/usr/bin/env python3
"""Writes BlowfishTables.swift: Blowfish's initial P-array and S-boxes.

Blowfish starts from the hexadecimal digits of the fractional part of pi:
the first 18 32-bit words are the P-array, the next 1024 the four S-boxes.
This computes pi with Machin's formula in integer arithmetic, so the table
comes from pi itself rather than from a copy.

Usage (from the repo root):
  apple/scripts/gen-blowfish-tables.py \
    > apple/FlightdeckKit/Sources/FlightdeckKit/SSH/KeyImport/BlowfishTables.swift
"""

WORDS = 18 + 4 * 256
BITS = WORDS * 32
GUARD = 64


def arctan_inv(x, one):
    """arctan(1/x) scaled by `one`."""
    total = term = one // x
    x2 = x * x
    n = 1
    sign = -1
    while term:
        term //= x2
        total += sign * (term // (2 * n + 1))
        sign = -sign
        n += 1
    return total


def main():
    one = 1 << (BITS + GUARD)
    pi = 4 * (4 * arctan_inv(5, one) - arctan_inv(239, one))
    frac = (pi - 3 * one) >> GUARD  # the fractional part, BITS bits
    words = [(frac >> (BITS - 32 * (i + 1))) & 0xFFFFFFFF for i in range(WORDS)]
    assert words[0] == 0x243F6A88 and words[18] == 0xD1310BA6

    def block(name, ws):
        out = [f"    static let {name}: [UInt32] = ["]
        for i in range(0, len(ws), 6):
            out.append("        " + ", ".join(f"0x{w:08X}" for w in ws[i:i + 6]) + ",")
        out.append("    ]")
        return "\n".join(out)

    print("// Generated by apple/scripts/gen-blowfish-tables.py. Do not edit.")
    print("// Blowfish's initial state: the hexadecimal digits of pi's fractional part.")
    print()
    print("enum BlowfishTables {")
    print(block("p", words[:18]))
    for s in range(4):
        print(block(f"s{s}", words[18 + 256 * s:18 + 256 * (s + 1)]))
    print("}")


main()
